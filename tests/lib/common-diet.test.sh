#!/usr/bin/env bash
# Диета _common.md: прозу режем, контракт — нет (спека §5, task-6-brief).
#
# Две проверки:
#   1. Размер файла целиком <= 8192 байт (бюджет диеты).
#   2. Контрактный хвост файла — всё от заголовка "## Что ты НЕ делаешь
#      (общие границы)" до EOF (границы, Готов когда, Stop&Ask,
#      Defer&Continue, Что не исполнялось, Формат отчёта) — байт-в-байт
#      равен зафиксированному здесь эталону. Проверка по offset+diff, а не
#      просто "заголовки на месте": имени заголовка мало, чтобы поймать
#      правку ВНУТРИ контрактной секции, которая не трогает сам заголовок.
set -u
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$(cd "$here/../.." && pwd)"
fail=0
f="$repo_root/skills/bootstrap/templates/_common.md"

if [ ! -f "$f" ]; then
  echo "FAIL: файл не найден: $f" >&2
  exit 1
fi

size="$(wc -c <"$f" | tr -d ' ')"
[ "$size" -le 8192 ] || { echo "FAIL: _common.md = $size байт, диета требует <= 8192" >&2; fail=1; }

heading="## Что ты НЕ делаешь (общие границы)"
offset="$(grep -boF "$heading" "$f" | head -1 | cut -d: -f1)"
if [ -z "$offset" ]; then
  echo "FAIL: контрактная секция исчезла: $heading" >&2
  fail=1
else
  actual_tail="$(mktemp)"
  expected_tail="$(mktemp)"
  trap 'rm -f "$actual_tail" "$expected_tail"' EXIT
  tail -c "+$((offset + 1))" "$f" > "$actual_tail"
  cat > "$expected_tail" << 'COMMON_TAIL_FIXTURE_EOF'
## Что ты НЕ делаешь (общие границы)

- Не пишешь deploy-конфиги, CI, Dockerfile вне ролей devops-engineer
- Не правишь файлы вне своей границы, даже если "там лучше было бы исправить"
- Не делаешь `git commit` — коммит собирает finalize-шаг пайплайна; оставь
  изменения как есть, staged или unstaged
- Не накапливаешь несвязанные изменения в одном коммите
- Не оставляешь TODO/FIXME без записи в своём report-файле
- Не используешь `any`/`Any` без явного обоснования рядом
- Не маскируешь ошибки `try/except: pass` или `.catch(() => {})`
- Не вызываешь приватные API других сервисов через прямой импорт. Только
  публичный контракт.

---

## Готов когда

- Реализация полностью покрывает требования брифа
- `bash .mvp/ci-mirror.sh` проходит с кодом 0 (это зеркало CI —
  не изобретай замену)
- Новый код покрыт тестами, тесты зелёные
- `git status` не показывает изменений вне `BOUNDARY` (и вне твоего
  report-файла)
- `REPORT_PATH` написан: интерфейсный дайджест для зависимых задач, а не
  прозаический рассказ

---

## Когда поднимать Stop&Ask

Запиши в `.mvp/blockers.md` с тегом `stop-and-ask` и завершись
статусом `BLOCKED`/`NEEDS_CONTEXT` если:

- Требуется изменить публичный контракт уже используемый другим сервисом из
  плана
- Текущая задача требует выйти за границы своего сервиса/модуля
- В коде обнаружен security-чувствительный паттерн (plain-text credentials,
  отсутствие валидации auth, открытый CORS на проде)
- Не получается выполнить задачу без выбора между несколькими равнозначными
  подходами с долгосрочными последствиями

---

## Когда применять Defer&Continue

Принимай решение сам и фиксируй его в СВОЁМ report-файле
(`.mvp/reports/task-<id>.md`), в секции `## Deferred decisions`,
строкой `<решение> — <обоснование>`:

- Имя переменной / приватной функции
- Trade-off между двумя похожими реализациями (производительность ≈
  читаемость)
- Выбор стандартного утилитарного подхода (Map vs object literal и т. п.)

В `.mvp/decisions.log` ты не пишешь — этот журнал наполняют
finalize-шаг и главная сессия, по твоему отчёту. Одна запись, один автор.

---

## Что не исполнялось — обязательная секция отчёта

Часть сделанного бывает невозможно ЗАПУСТИТЬ: нет целевой ОС, нет внешнего
сервиса, нет железа. Это не повод молчать и не повод объявлять задачу
проваленной — это повод сказать прямо. Заводи в `REPORT_PATH` секцию
`## Not executed` со строками `<что> — <почему> — <чем заменено>` и
продублируй её одной строкой в concerns финального блока.

Вычитанный построчно код — не исполненный код. Разницу должны видеть
ревьюер и оператор сразу, а не выуживать из прозы в середине отчёта.
Запускать было нечего — секции нет; пустая «на всякий случай» только шумит.

---

## Формат отчёта об окончании (status-contract)

После завершения задачи верни финальный блок ≤ 15 строк. Эти токены
грепаются пайплайном — держи их в начале строки, заглавными:

```
STATUS: DONE|DONE_WITH_CONCERNS|BLOCKED|NEEDS_CONTEXT
FILES: <файлы через запятую>
```

- `DONE` — задача полностью выполнена, все критерии готовности (см. "Готов
  когда" выше) закрыты.
- `DONE_WITH_CONCERNS` — выполнена, но есть trade-off/допущение, о котором
  должен знать ревьюер.
- `BLOCKED` — задача НЕ выполнена, дальше двигаться нельзя без решения
  оператора/родительского процесса (см. "Когда поднимать Stop&Ask" выше).
- `NEEDS_CONTEXT` — задача НЕ выполнена, не хватает информации (контракт,
  бриф, соседний файл), которую нельзя выдумать.

После этих двух строк допустимы 1–3 короткие строки concerns — и ничего
больше: детали живут в `REPORT_PATH`.

`FILES:` — только файлы, реально изменённые в рамках текущей задачи (должно
совпадать с `git status`). Никогда не молчи о `BLOCKED`/`NEEDS_CONTEXT`,
выдавая частичный результат за `DONE`.
COMMON_TAIL_FIXTURE_EOF

  if ! diff -u "$expected_tail" "$actual_tail" >/tmp/common-diet-tail.diff 2>&1; then
    echo "FAIL: контрактный хвост (от \"$heading\" до EOF) отличается от эталона байт-в-байт:" >&2
    cat /tmp/common-diet-tail.diff >&2
    fail=1
  fi
fi

for heading2 in "## Когда поднимать Stop&Ask" "## Что не исполнялось — обязательная секция отчёта" "## Формат отчёта об окончании (status-contract)"; do
  grep -qF "$heading2" "$f" || { echo "FAIL: контрактная секция исчезла: $heading2" >&2; fail=1; }
done
grep -qF "STATUS:" "$f" || { echo "FAIL: STATUS-контракт исчез" >&2; fail=1; }

exit $fail
